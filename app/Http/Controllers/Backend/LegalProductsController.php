    /**
     * Update the specified resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @param  int  $id
     * @return \Illuminate\Http\Response
     */
    public function update(Request $request, $id)
    {
        $message;
        try {
                
            $legal_products = LegalProducts::find($id);
            $legal_products->title = $request->get('title_legal_products');
            $legal_products->description = $request->get('description_legal_products');
            $legal_products->save();
     
            $message = "Legales de Productos: ".$request->get('title_legal_products')." editado con exito!";
            
            return redirect('/admin/settings/legal_products')->with('message', $message);
        
        } catch(\Exception $e) {

            if(\Config::get('app.debug'))
                    $message = 'ERROR('.$e->getLine().'): '.$e->getMessage();
            else
                    $message = 'Se ha producido un error. Por favor intente nuevamente.';

            $respuesta = array(
                    'estado' => false,
                    'mensaje' => $message
            );

            return \Response::json($respuesta);
	}
    }

